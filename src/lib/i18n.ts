export type TranslationKey = keyof (typeof DICTIONARY)['en']

export function getTranslation(key: TranslationKey, lang: Language, values?: Record<string, string | number>): string {
  const dictionary = DICTIONARY[lang] as Record<string, string> | undefined
  const fallback = DICTIONARY.en as Record<string, string>
  const text = dictionary?.[key] ?? fallback[key] ?? key
  return values ? text.replace(/\{(\w+)\}/g, (placeholder, name: string) => String(values[name] ?? placeholder)) : text
}

export function useTranslation() {
  const language = useSettingsStore((state) => state.language)
  const setLanguage = useSettingsStore((state) => state.setLanguage)

  return {
    language,
    setLanguage,
    t: (key: TranslationKey, values?: Record<string, string | number>): string => getTranslation(key, language, values),
  }
}
