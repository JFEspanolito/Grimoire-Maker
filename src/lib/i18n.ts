export type TranslationKey = keyof (typeof DICTIONARY)['en']

export function getTranslation(key: TranslationKey, lang: Language): string {
  const dictionary = DICTIONARY[lang] as Record<string, string> | undefined
  const fallback = DICTIONARY.en as Record<string, string>
  return dictionary?.[key] ?? fallback[key] ?? key
}

export function useTranslation() {
  const language = useSettingsStore((state) => state.language)
  const setLanguage = useSettingsStore((state) => state.setLanguage)

  return {
    language,
    setLanguage,
    t: (key: TranslationKey): string => getTranslation(key, language),
  }
}
